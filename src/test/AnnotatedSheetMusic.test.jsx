// Mock OpenSheetMusicDisplay because jsdom does not fully support
// the SVG rendering features required by the real library.
const osmdMock = vi.hoisted(() => ({
  load: vi.fn(),
  render: vi.fn(),
  instances: [],
  skipSvg: false,
}))

vi.mock('opensheetmusicdisplay', () => ({
  OpenSheetMusicDisplay: class {
    constructor(container, options) {
      this.container = container
      this.options = options
      this.Zoom = 1

      // Create two instruments to test part-index matching.
      const instruments = [
        { Name: 'Piano' },
        { Name: 'Violin' },
      ]

      // Create a simplified score containing measures 0 through 8.
      // Measure 0 represents a pickup measure.
      this.Sheet = {
        Instruments: instruments,

        SourceMeasures: Array.from(
          { length: 9 },
          (_, measureNumber) => ({
            MeasureNumber: measureNumber,

            VerticalSourceStaffEntryContainers: Array.from(
              { length: 4 },
              (_, offset) => ({
                StaffEntries: instruments.map((instrument) => ({
                  ParentStaff: {
                    ParentInstrument: instrument,
                  },

                  VoiceEntries: [
                    {
                      Timestamp: {
                        RealValue: offset / 4,
                      },

                      Notes: [64, 69, 72, 77].map((midi) => ({
                        isRest: () => false,
                        halfTone: midi - 12,
                        NoteheadColor: undefined,
                        NoteColor: undefined,
                      })),
                    },
                  ],
                })),
              })
            ),
          })
        ),
      }

      osmdMock.instances.push(this)
    }

    async load(xml) {
      return osmdMock.load(xml)
    }

    render() {
      osmdMock.render()

      // Allow tests to simulate missing SVG output.
      if (osmdMock.skipSvg) return

      const svgNamespace = 'http://www.w3.org/2000/svg'

      const svg = document.createElementNS(
        svgNamespace,
        'svg'
      )

      const group = document.createElementNS(
        svgNamespace,
        'g'
      )

      // Simulate the visible notation bounds.
      group.getBBox = () => ({
        x: 10,
        y: 20,
        width: 400,
        height: 120,
      })

      svg.appendChild(group)

      // Simulate the highlighted noteheads generated by OSMD.
      this.Sheet.SourceMeasures.forEach((measure) => {
        measure.VerticalSourceStaffEntryContainers.forEach(
          (container) => {
            container.StaffEntries.forEach((staffEntry) => {
              staffEntry.VoiceEntries.forEach((voiceEntry) => {
                voiceEntry.Notes.forEach((note) => {
                  if (!note.NoteheadColor) return

                  const notehead = document.createElementNS(
                    svgNamespace,
                    'path'
                  )

                  notehead.setAttribute(
                    'fill',
                    note.NoteheadColor
                  )

                  notehead.setAttribute(
                    'stroke',
                    note.NoteColor
                  )

                  notehead.setAttribute(
                    'data-test-note',
                    'true'
                  )

                  notehead.setAttribute(
                    'data-measure',
                    String(measure.MeasureNumber)
                  )

                  notehead.setAttribute(
                    'data-part',
                    String(
                      this.Sheet.Instruments.indexOf(
                        staffEntry.ParentStaff.ParentInstrument
                      )
                    )
                  )

                  notehead.setAttribute(
                    'data-offset',
                    String(
                      voiceEntry.Timestamp.RealValue * 4
                    )
                  )

                  notehead.setAttribute(
                    'data-midi',
                    String(note.halfTone + 12)
                  )

                  group.appendChild(notehead)
                })
              })
            })
          }
        )
      })

      this.container.appendChild(svg)
    }
  },
}))

