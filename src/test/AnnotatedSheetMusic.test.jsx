// Find a source note using its actual score information.
function getSourceNote(
  measureNumber,
  partIndex,
  offset,
  midi
) {
  const instance = osmdMock.instances[0]

  const measure = instance.Sheet.SourceMeasures.find(
    (item) => item.MeasureNumber === measureNumber
  )

  const container =
    measure.VerticalSourceStaffEntryContainers[offset]

  const staffEntry = container.StaffEntries[partIndex]

  return staffEntry.VoiceEntries[0].Notes.find(
    (note) => note.halfTone + 12 === midi
  )
}

// Retrieve a highlighted note by its accessible label.
function getHighlightedNote(error) {
  return screen.getByRole('button', {
    name: `${error.label}, measure ${error.measure}, note ${error.expectedNote}`,
  })
}

// Retrieve the selected note's error details panel.
function getErrorDetails() {
  return document.querySelector(
    '.annotated-sheet-music-error-details'
  )
}

// Retrieve all highlighted SVG noteheads.
function getHighlightedNoteheads() {
  return Array.from(
    document.querySelectorAll('[data-test-note="true"]')
  )
}

// Render valid MusicXML with backend annotations.
async function renderValidScore(
  scoreAnnotations = BACKEND_ANNOTATIONS
) {
  const result = render(
    <AnnotatedSheetMusic
      musicXML={VALID_XML}
      scoreAnnotations={scoreAnnotations}
    />
  )

  await waitFor(() => {
    expect(osmdMock.render).toHaveBeenCalled()

    expect(
      screen.queryByText('Loading sheet music...')
    ).not.toBeInTheDocument()
  })

  return result
}

