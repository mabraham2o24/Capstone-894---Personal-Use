
import { beforeEach, describe, expect, test, vi } from 'vitest'
import { render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import AnnotatedSheetMusic from '../components/AnnotatedSheetMusic.jsx'

// Mock OpenSheetMusicDisplay because jsdom does not fully support
// the SVG rendering features required by the real library.
const osmdMock = vi.hoisted(() => ({
  load: vi.fn(),
  render: vi.fn(),
  instances: [],
}))

vi.mock('opensheetmusicdisplay', () => ({
  OpenSheetMusicDisplay: class {
    constructor(container, options) {
      this.container = container
      this.options = options
      this.Zoom = 1

      // Create a simplified eight-measure score.
      this.Sheet = {
        SourceMeasures: Array.from({ length: 8 }, () => ({
          VerticalSourceStaffEntryContainers: [
            {
              StaffEntries: [
                {
                  VoiceEntries: [
                    {
                      Notes: Array.from({ length: 4 }, () => ({
                        isRest: () => false,
                        NoteheadColor: undefined,
                        NoteColor: undefined,
                      })),
                    },
                  ],
                },
              ],
            },
          ],
        })),
      }

      osmdMock.instances.push(this)
    }

    async load(xml) {
      return osmdMock.load(xml)
    }

    render() {
      osmdMock.render()

      const svgNamespace = 'http://www.w3.org/2000/svg'
      const svg = document.createElementNS(svgNamespace, 'svg')
      const group = document.createElementNS(svgNamespace, 'g')

      // Simulate the visible notation bounds.
      group.getBBox = () => ({
        x: 10,
        y: 20,
        width: 400,
        height: 120,
      })

      svg.appendChild(group)

      // Simulate the four highlighted noteheads generated by OSMD.
      this.Sheet.SourceMeasures.forEach((measure) => {
        const notes =
          measure.VerticalSourceStaffEntryContainers[0]
            .StaffEntries[0].VoiceEntries[0].Notes

        notes.forEach((note) => {
          if (!note.NoteheadColor) return

          const notehead = document.createElementNS(
            svgNamespace,
            'path'
          )

          notehead.setAttribute('fill', note.NoteheadColor)
          notehead.setAttribute('data-test-note', 'true')

          group.appendChild(notehead)
        })
      })

      this.container.appendChild(svg)
    }
  },
}))

const VALID_XML = `<?xml version="1.0" encoding="utf-8"?>
<score-partwise version="4.0">
  <part-list>
    <score-part id="P1">
      <part-name>Piano</part-name>
    </score-part>
  </part-list>
  <part id="P1">
    <measure number="1"/>
  </part>
</score-partwise>`

const XML_WITHOUT_INSTRUMENT = `
<score-partwise version="4.0">
  <part-list></part-list>
  <part id="P1"></part>
</score-partwise>`

const MOCK_ERROR_NOTES = [
  {
    type: 'Incorrect Pitch',
    measure: 1,
    note: 'E4',
    color: '#ef4444',
    description:
      'The performed pitch does not match the expected E4 note.',
  },
  {
    type: 'Timing Error',
    measure: 2,
    note: 'C5',
    color: '#eab308',
    description:
      'The note was played earlier or later than its expected position.',
  },
  {
    type: 'Duration Error',
    measure: 3,
    note: 'F5',
    color: '#f97316',
    description:
      'The note was held for a different duration than expected.',
  },
  {
    type: 'Missing Note',
    measure: 5,
    note: 'F4',
    color: '#a855f7',
    description:
      'The expected note was not detected in the performance.',
  },
]

function getSourceNote(measureNumber, noteIndex) {
  const instance = osmdMock.instances[0]

  return instance.Sheet.SourceMeasures[measureNumber - 1]
    .VerticalSourceStaffEntryContainers[0]
    .StaffEntries[0]
    .VoiceEntries[0]
    .Notes[noteIndex]
}

async function renderValidScore() {
  render(<AnnotatedSheetMusic musicXML={VALID_XML} />)

  await waitFor(() => {
    expect(osmdMock.render).toHaveBeenCalled()
  })

  await screen.findByRole('button', {
    name: 'Incorrect Pitch, measure 1, note E4',
  })
}

beforeEach(() => {
  vi.clearAllMocks()
  osmdMock.instances.length = 0
  osmdMock.load.mockResolvedValue(undefined)
})

describe('Annotated Sheet Music - Sprint 4 Frontend Tests', () => {
  // TEST 1: Verify that the section is displayed.
  test('displays the Annotated Sheet Music section', () => {
    render(<AnnotatedSheetMusic musicXML="" />)

    expect(
      screen.getByRole('heading', {
        name: 'Annotated Sheet Music',
      })
    ).toBeInTheDocument()

    expect(
      screen.getByText(/Click a highlighted note/i)
    ).toBeInTheDocument()
  })

  // TEST 2: Verify that missing MusicXML is handled.
  test('displays a message when MusicXML is missing', () => {
    render(<AnnotatedSheetMusic musicXML="" />)

    expect(
      screen.getByText(
        'No MusicXML score is available to display.'
      )
    ).toBeInTheDocument()

    expect(osmdMock.load).not.toHaveBeenCalled()
  })

  // TEST 3: Verify that valid MusicXML is loaded.
  test('loads valid MusicXML into OpenSheetMusicDisplay', async () => {
    await renderValidScore()

    expect(osmdMock.load).toHaveBeenCalledWith(VALID_XML)
    expect(osmdMock.render).toHaveBeenCalled()
  })

  // TEST 4: Verify the instrument name.
  test('displays the instrument name from MusicXML', async () => {
    await renderValidScore()

    expect(
      screen.getByRole('heading', { name: 'Piano' })
    ).toBeInTheDocument()
  })

  // TEST 5: Verify fallback instrument name.
  test('uses a fallback name when instrument is missing', async () => {
    render(
      <AnnotatedSheetMusic
        musicXML={XML_WITHOUT_INSTRUMENT}
      />
    )

    await waitFor(() => {
      expect(
        screen.getByRole('heading', { name: 'Instrument' })
      ).toBeInTheDocument()
    })
  })

  // TEST 6: Verify that invalid MusicXML is handled.
  test('displays an error for invalid MusicXML', async () => {
    const consoleSpy = vi
      .spyOn(console, 'error')
      .mockImplementation(() => {})

    try {
      render(
        <AnnotatedSheetMusic
          musicXML="<score-partwise><invalid></score-partwise>"
        />
      )

      expect(
        await screen.findByRole('alert')
      ).toHaveTextContent(
        'Unable to display the MusicXML score.'
      )

      expect(osmdMock.load).not.toHaveBeenCalled()
    } finally {
      consoleSpy.mockRestore()
    }
  })

  // TEST 7: Verify OpenSheetMusicDisplay configuration.
  test('uses SVG rendering and the correct zoom level', async () => {
    await renderValidScore()

    const instance = osmdMock.instances[0]

    expect(instance.options).toMatchObject({
      autoResize: false,
      backend: 'svg',
      drawTitle: false,
      drawPartNames: false,
      drawPartAbbreviations: false,
    })

    expect(instance.Zoom).toBe(1.2)
  })

  // TEST 8: Verify all four error highlight colors.
  test('applies the correct colors to mock error notes', async () => {
    await renderValidScore()

    const targetNotes = [
      getSourceNote(1, 0),
      getSourceNote(2, 1),
      getSourceNote(3, 0),
      getSourceNote(5, 0),
    ]

    targetNotes.forEach((note, index) => {
      expect(note.NoteheadColor).toBe(
        MOCK_ERROR_NOTES[index].color
      )

      expect(note.NoteColor).toBe(
        MOCK_ERROR_NOTES[index].color
      )
    })
  })

  // TEST 9: Verify that highlighted noteheads are rendered.
  test('renders four colored noteheads', async () => {
    await renderValidScore()

    const noteheads = document.querySelectorAll(
      '[data-test-note="true"]'
    )

    expect(noteheads).toHaveLength(4)

    expect(
      Array.from(noteheads).map((note) =>
        note.getAttribute('fill')
      )
    ).toEqual(MOCK_ERROR_NOTES.map((error) => error.color))
  })

  // TEST 10: Verify clickable note accessibility.
  test('makes highlighted notes accessible as buttons', async () => {
    await renderValidScore()

    MOCK_ERROR_NOTES.forEach((error) => {
      const note = screen.getByRole('button', {
        name: `${error.type}, measure ${error.measure}, note ${error.note}`,
      })

      expect(note).toHaveAttribute('tabindex', '0')
      expect(note).toHaveStyle({ cursor: 'pointer' })
    })
  })

  // TEST 11: Verify the details for each error type.
  test.each(MOCK_ERROR_NOTES)(
    'displays details when clicking $type',
    async (error) => {
      const user = userEvent.setup()

      await renderValidScore()

      await user.click(
        screen.getByRole('button', {
          name: `${error.type}, measure ${error.measure}, note ${error.note}`,
        })
      )

      const details = document.querySelector(
        '.annotated-sheet-music-error-details'
      )

      expect(details).toBeInTheDocument()

      expect(
        within(details).getByRole('heading', {
          name: error.type,
        })
      ).toBeInTheDocument()

      expect(details).toHaveTextContent(
        `Measure: ${error.measure}`
      )

      expect(details).toHaveTextContent(
        `Expected Note: ${error.note}`
      )

      expect(details).toHaveTextContent(error.description)
      expect(details).toHaveStyle({
        border: `1px solid ${error.color}`,
      })
    }
  )

  // TEST 15: Verify that the error panel can be closed.
  test('closes error details when clicking the X button', async () => {
    const user = userEvent.setup()

    await renderValidScore()

    await user.click(
      screen.getByRole('button', {
        name: 'Incorrect Pitch, measure 1, note E4',
      })
    )

    expect(
      document.querySelector(
        '.annotated-sheet-music-error-details'
      )
    ).toBeInTheDocument()

    await user.click(
      screen.getByRole('button', {
        name: 'Close error details',
      })
    )

    expect(
      document.querySelector(
        '.annotated-sheet-music-error-details'
      )
    ).not.toBeInTheDocument()
  })

  // TEST 16: Verify Enter-key interaction.
  test('opens error details using the Enter key', async () => {
    const user = userEvent.setup()

    await renderValidScore()

    const note = screen.getByRole('button', {
      name: 'Timing Error, measure 2, note C5',
    })

    note.focus()
    await user.keyboard('{Enter}')

    expect(
      screen.getByRole('heading', {
        name: 'Timing Error',
      })
    ).toBeInTheDocument()
  })

  // TEST 17: Verify Space-key interaction.
  test('opens error details using the Space key', async () => {
    const user = userEvent.setup()

    await renderValidScore()

    const note = screen.getByRole('button', {
      name: 'Duration Error, measure 3, note F5',
    })

    note.focus()
    await user.keyboard(' ')

    expect(
      screen.getByRole('heading', {
        name: 'Duration Error',
      })
    ).toBeInTheDocument()
  })

  // TEST 18: Verify SVG sizing.
  test('calculates SVG dimensions with padding', async () => {
    await renderValidScore()

    const svg = document.querySelector(
      '.annotated-sheet-music-container svg'
    )

    expect(svg).toBeInTheDocument()

    expect(svg).toHaveAttribute(
      'viewBox',
      '-22 -4 464 168'
    )

    expect(svg).toHaveAttribute('width', '464')
    expect(svg).toHaveAttribute('height', '168')

    await waitFor(() => {
      expect(
        document.querySelector(
          '.annotated-sheet-music-wrapper'
        )
      ).toHaveStyle({ width: '504px' })
    })
  })

  // TEST 19: Verify that an OSMD loading failure is handled.
  test('displays an error if the score cannot be loaded', async () => {
    const consoleSpy = vi
      .spyOn(console, 'error')
      .mockImplementation(() => {})

    osmdMock.load.mockRejectedValueOnce(
      new Error('Unable to load score')
    )

    try {
      render(<AnnotatedSheetMusic musicXML={VALID_XML} />)

      expect(
        await screen.findByRole('alert')
      ).toHaveTextContent(
        'Unable to display the MusicXML score.'
      )
    } finally {
      consoleSpy.mockRestore()
    }
  })

  // TEST 20: Verify that missing SVG output is handled.
  test('displays an error if OSMD generates no SVG', async () => {
    const consoleSpy = vi
      .spyOn(console, 'error')
      .mockImplementation(() => {})

    osmdMock.render.mockImplementationOnce(() => {
      throw new Error('SVG rendering failed')
    })

    try {
      render(<AnnotatedSheetMusic musicXML={VALID_XML} />)

      expect(
        await screen.findByRole('alert')
      ).toHaveTextContent(
        'Unable to display the MusicXML score.'
      )
    } finally {
      consoleSpy.mockRestore()
    }
  })
})
