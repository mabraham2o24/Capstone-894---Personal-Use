// Create a simulated backend annotation response.
function createAnnotation(error, overrides = {}) {
  return {
    note_id: `p0_m${error.measure}_q${error.offset}_${error.expectedNote}`,
    part_index: 0,
    measure: error.measure,
    offset_in_measure: error.offset,
    midi: error.midi,
    beat: error.offset + 1,
    expected_note: error.expectedNote,
    played_note: error.playedNote,

    errors: [
      {
        type: error.type,
        category: error.category,
        description: error.description,
      },
    ],

    ...overrides,
  }
}

// Simulated backend response containing all six error types.
const BACKEND_ANNOTATIONS = {
  notes: ERROR_CASES.map((error) =>
    createAnnotation(error)
  ),
  additional_notes: [],
}

// Simulated backend response without performance errors.
const EMPTY_ANNOTATIONS = {
  notes: [],
  additional_notes: [],
}

// Simulated extra note that does not exist in the score.
