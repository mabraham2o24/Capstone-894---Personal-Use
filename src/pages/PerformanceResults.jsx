
import { useLocation, useNavigate } from 'react-router-dom'

function PerformanceResults() {
  // Allows navigation between application pages.
  const navigate = useNavigate()

  // Gets the practice session, score, and audio-analysis
  // information passed from the Performance Upload page.
  const location = useLocation()

  const sessionId = location.state?.sessionId
  const scoreResult = location.state?.scoreResult
  const audioResult = location.state?.audioResult

  // Gets the selected measure range.
  const startMeasure = location.state?.startMeasure
  const endMeasure = location.state?.endMeasure

  // Gets the note-level feedback returned by the backend.
  const noteFeedback = audioResult?.note_feedback ?? []

  // Makes feedback status values easier to read.
  const formatStatus = (status) => {
    if (status == null || status === '') {
      return 'Not available'
    }

    return String(status).replace(/_/g, ' ')
  }

  // Assigns a visual style to each feedback status.
  const getStatusClass = (status) => {
    if (status == null || status === '') {
      return 'feedback-status-neutral'
    }

    const normalizedStatus = String(status)
      .toLowerCase()
      .replace(/_/g, ' ')
      .trim()

    if (
      normalizedStatus === 'correct' ||
      normalizedStatus === 'on time'
    ) {
      return 'feedback-status-success'
    }

    if (
      normalizedStatus === 'incorrect' ||
      normalizedStatus === 'missing' ||
      normalizedStatus === 'additional'
    ) {
      return 'feedback-status-error'
    }

    if (
      normalizedStatus === 'early' ||
      normalizedStatus === 'late' ||
      normalizedStatus === 'too short' ||
      normalizedStatus === 'too long'
    ) {
      return 'feedback-status-warning'
    }

    return 'feedback-status-neutral'
  }

  // Displays missing or unavailable note information clearly.
  const formatValue = (value) => {
    if (value == null || value === '') {
      return 'N/A'
    }

    return String(value)
  }

  // Prevents the page from causing an error if it is opened
  // without first uploading and processing a performance.
  if (!sessionId || !audioResult) {
    return (
      <div className="performance-results-page">
        <div className="performance-card">
          <h1>Performance Processing</h1>

          <p className="message">
            No processed performance is available.
          </p>

          <button
            className="back-button"
            onClick={() => navigate('/dashboard')}
          >
            ← Back to Dashboard
          </button>
        </div>
      </div>
    )
  }

  return (
    <div className="performance-results-page">
      <div className="performance-card">

        <button
          className="back-button"
          onClick={() =>
            navigate('/performance-upload', {
              state: {
                sessionId: sessionId,
                scoreResult: scoreResult,
                startMeasure: startMeasure,
                endMeasure: endMeasure,
              },
            })
          }
        >
          ← Back to Performance Upload
        </button>

        <h1>Performance Processing</h1>

        <p className="success-text">
          Audio successfully processed.
        </p>

        {/* General information about the analyzed performance */}
        <div className="summary-grid">
          <div>
            <span>Session ID</span>
            <strong>{sessionId}</strong>
          </div>

          <div>
            <span>Audio File</span>
            <strong>{audioResult.filename}</strong>
          </div>

          <div>
            <span>Status</span>
            <strong>{audioResult.status}</strong>
          </div>

          <div>
            <span>Detected Pitches</span>
            <strong>
              {audioResult.detected_pitches?.length ?? 0}
            </strong>
          </div>

          <div>
            <span>Total Note Events</span>
            <strong>
              {audioResult.note_events?.length ?? 0}
            </strong>
          </div>

          <div>
            <span>Starting Measure</span>
            <strong>{formatValue(startMeasure)}</strong>
          </div>

          <div>
            <span>Ending Measure</span>
            <strong>{formatValue(endMeasure)}</strong>
          </div>
        </div>

        {/* Displays the feedback generated by the backend */}
        <div className="performance-section">
          <h2>Performance Feedback</h2>

          <p className="subtitle">
            Review the pitch, timing, and note duration
            feedback for your selected measures.
          </p>

          {noteFeedback.length === 0 ? (
            <p className="message">
              No note-level feedback was returned for this performance.
            </p>
          ) : (
            <div className="table-container">
              <table className="notes-table">
                <thead>
                  <tr>
                    <th>Measure</th>
                    <th>Beat</th>
                    <th>Expected Note</th>
                    <th>Played Note</th>
                    <th>Pitch Status</th>
                    <th>Expected Length</th>
                    <th>Played Length</th>
                    <th>Duration Status</th>
                    <th>Timing Status</th>
                  </tr>
                </thead>

                <tbody>
                  {noteFeedback.map((feedback, index) => (
                    <tr key={index}>
                      <td>{formatValue(feedback.measure)}</td>

                      <td>{formatValue(feedback.beat)}</td>

                      <td>
                        {formatValue(feedback.expected_note)}
                      </td>

                      <td>
                        {formatValue(feedback.played_note)}
                      </td>

                      <td>
                        <span
                          className={`feedback-status ${getStatusClass(feedback.pitch_status)}`}
                        >
                          {formatStatus(feedback.pitch_status)}
                        </span>
                      </td>

                      <td>
                        {formatValue(feedback.expected_note_length)}
                      </td>

                      <td>
                        {formatValue(feedback.played_note_length)}
                      </td>

                      <td>
                        <span
                          className={`feedback-status ${getStatusClass(feedback.duration_status)}`}
                        >
                          {formatStatus(feedback.duration_status)}
                        </span>
                      </td>

                      <td>
                        <span
                          className={`feedback-status ${getStatusClass(feedback.timing_status)}`}
                        >
                          {formatStatus(feedback.timing_status)}
                        </span>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </div>

        {/* Displays the pitches detected in the audio */}
        <div className="performance-section">
          <h2>Detected Pitches</h2>

          <p className="detected-pitches">
            {audioResult.detected_pitches?.length
              ? audioResult.detected_pitches.join(', ')
              : 'No pitches detected.'}
          </p>
        </div>

        <div className="page-actions">
          <button
            className="upload-button"
            onClick={() => navigate('/dashboard')}
          >
            Back to Dashboard
          </button>
        </div>

      </div>
    </div>
  )
}

export default PerformanceResults
